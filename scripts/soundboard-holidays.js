#!/usr/bin/env node
"use strict";
/* Holiday page upkeep for /soundboard/ (runs in scripts/publish.sh before the build, and daily via
   soundboard-add-johnny.js --upkeep). Uses data/holidays.json and the date (CT) at build time:
   - page visible (show_before_days before the date through the day): clips archived in data/holiday-archive/<key>.json are restored to data/soundboard.json
   - page hidden (from the day after): its clips move from data/soundboard.json into data/holiday-archive/<key>.json. Audio in sb-audio/ is never touched or deleted.
   - writes soundboard/holidays.json (pages that exist + whether each is visible), which sb.js reads for the tabs.
   Usage: node scripts/soundboard-holidays.js [--today YYYY-MM-DD] [--dry-run]   Prints a JSON summary; exit 0. */
const fs = require("fs");
const path = require("path");
const H = require("./lib/holidays");
const D = require("./lib/docs");
const argv = process.argv.slice(2);
const ti = argv.indexOf("--today");
const TODAY = ti >= 0 ? argv[ti + 1] : D.todayCT();
const DRY = argv.includes("--dry-run");
function upkeep(today = TODAY, dry = DRY) {
  const cfg = H.load();
  const dataPath = path.join(H.ROOT, "data/soundboard.json");
  const data = JSON.parse(fs.readFileSync(dataPath, "utf8"));
  const pages = [], moved = { archived: 0, restored: 0 };
  let changed = false;
  for (const h of cfg.holidays) {
    const tag = "holiday-" + h.key;
    const arch = H.readArch(h.key);
    const live = data.clips.filter((c) => c.tag === tag);
    if (!h.page && !live.length && !arch.clips.length) continue;
    const w = H.windowFor(h, today), vis = H.visible(h, today);
    if (vis && arch.clips.length) {
      for (const c of arch.clips) if (!data.clips.some((x) => x.id === c.id)) { data.clips.push(c); moved.restored++; }
      arch.clips = []; if (!dry) H.writeArch(h.key, arch); changed = true;
    } else if (!vis && live.length) {
      for (const c of live) if (!arch.clips.some((x) => x.id === c.id)) arch.clips.push(c);
      data.clips = data.clips.filter((c) => c.tag !== tag); moved.archived += live.length;
      arch.archived = today; if (!dry) H.writeArch(h.key, arch); changed = true;
    }
    const n = vis ? data.clips.filter((c) => c.tag === tag).length : arch.clips.length;
    pages.push({ key: h.key, label: h.label, date: w.date, show_from: w.start, hide_from: w.end, visible: vis, clips: n, archived: !vis });
  }
  if (!dry) {
    if (changed) fs.writeFileSync(dataPath, JSON.stringify(data, null, 1) + "\n");
    const out = path.join(H.ROOT, "soundboard/holidays.json");
    fs.writeFileSync(out, JSON.stringify({ built: today, note: "Generated by scripts/soundboard-holidays.js from data/holidays.json. Do not edit.", pages }, null, 1) + "\n");
  }
  return { today, ...moved, pages };
}
module.exports = { upkeep };
if (require.main === module) console.log(JSON.stringify(upkeep()));
